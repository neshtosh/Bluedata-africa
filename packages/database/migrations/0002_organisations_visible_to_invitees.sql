-- Invited users must see the organisation that invited them (name, slug) before accepting.
-- Replaces app.is_active_member with app.is_member (active OR invited); the old name would have
-- been misleading. The function runs as the caller, so the memberships RLS policy still applies.
CREATE FUNCTION app.is_member(org uuid) RETURNS boolean
  LANGUAGE sql STABLE
  AS $$
    SELECT EXISTS (
      SELECT 1 FROM tenancy.memberships m
      WHERE m.organisation_id = org
        AND m.user_id = app.current_user_id()
        AND m.status IN ('active', 'invited')
    )
  $$;
